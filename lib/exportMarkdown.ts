import { ProjectPlan, IdeaRequest } from "./types";

export function generateMarkdownReport(plan: ProjectPlan, request?: IdeaRequest): string {
  const parts: string[] = [];

  parts.push(`# ${plan.projectTitle}\n`);
  parts.push(`> ${plan.solutionSummary}\n`);

  parts.push(`## 📌 Overview\n`);
  parts.push(`**Problem Statement:**\n${plan.problemStatement}\n`);
  parts.push(`**Solution Summary:**\n${plan.solutionSummary}\n`);

  if (request) {
    parts.push(`### Hackathon Context`);
    parts.push(`- **Category:** ${request.category}`);
    parts.push(`- **Duration:** ${request.duration}`);
    parts.push(`- **Team Skill Level:** ${request.skillLevel}`);
    if (request.technologies) {
      parts.push(`- **Preferred Stack:** ${request.technologies}`);
    }
    parts.push("");
  }

  parts.push(`### 🎯 Target Users`);
  plan.targetUsers.forEach((user) => parts.push(`- ${user}`));
  parts.push("");

  parts.push(`### 👤 User Stories`);
  plan.userStories.forEach((s) => {
    parts.push(`- **As a** ${s.role}, **I want to** ${s.action} **so that** ${s.benefit}.`);
  });
  parts.push("");

  parts.push(`## 🚀 MVP Features\n`);
  parts.push(`| # | Feature | Priority | Est. Hours | Description |`);
  parts.push(`|---|---|---|---|---|`);
  plan.mvpFeatures.forEach((f, idx) => {
    parts.push(
      `| ${idx + 1} | **${f.name}** | \`${f.priority || "must-have"}\` | ${f.estimatedHours ? `${f.estimatedHours}h` : "—"} | ${f.description} |`
    );
  });
  parts.push("");

  if (plan.futureFeatures && plan.futureFeatures.length > 0) {
    parts.push(`### 🔮 Future Features`);
    plan.futureFeatures.forEach((f) => {
      parts.push(`- **${f.name}:** ${f.description}`);
    });
    parts.push("");
  }

  parts.push(`## 🛠️ Recommended Tech Stack\n`);
  parts.push(`| Category | Technology | Rationale |`);
  parts.push(`|---|---|---|`);
  plan.techStack.forEach((t) => {
    parts.push(`| **${t.category}** | \`${t.technology}\` | ${t.reasoning} |`);
  });
  parts.push("");

  parts.push(`## 📐 System Architecture\n`);
  parts.push("```mermaid");
  // Clean mermaid source of existing backticks
  const cleanDiagram = plan.mermaidDiagram
    .replace(/^```(?:mermaid)?\s*\n?/i, "")
    .replace(/\n?```\s*$/i, "")
    .trim();
  parts.push(cleanDiagram);
  parts.push("```\n");

  parts.push(`## 🔌 API Design\n`);
  plan.apiEndpoints.forEach((ep) => {
    parts.push(`### \`${ep.method}\` ${ep.path}`);
    parts.push(`${ep.description}\n`);
    if (ep.requestExample) {
      parts.push(`**Request Example:**\n\`\`\`json\n${ep.requestExample}\n\`\`\`\n`);
    }
    if (ep.responseExample) {
      parts.push(`**Response Example:**\n\`\`\`json\n${ep.responseExample}\n\`\`\`\n`);
    }
  });

  parts.push(`## 🗄️ Database Schema\n`);
  plan.databaseTables.forEach((table) => {
    parts.push(`### Table: \`${table.tableName}\``);
    if (table.relationships) {
      parts.push(`*Relationships: ${table.relationships}*\n`);
    }
    parts.push(`| Field | Type | Constraints |`);
    parts.push(`|---|---|---|`);
    table.fields.forEach((f) => {
      parts.push(`| \`${f.name}\` | \`${f.type}\` | ${f.constraints || "—"} |`);
    });
    parts.push("");
  });

  parts.push(`## ⏱️ Implementation Roadmap\n`);
  plan.roadmap.forEach((phase) => {
    parts.push(`### ${phase.phase} (${phase.timeBox})`);
    phase.tasks.forEach((task) => {
      parts.push(`- [ ] ${task}`);
    });
    parts.push("");
  });

  parts.push(`## ✅ Testing & QA Checklist\n`);
  plan.testingChecklist.forEach((t) => {
    parts.push(`- [ ] ${t}`);
  });
  parts.push("");

  if (plan.risks && plan.risks.length > 0) {
    parts.push(`## ⚠️ Risks & Mitigations\n`);
    parts.push(`| Risk | Severity | Mitigation |`);
    parts.push(`|---|---|---|`);
    plan.risks.forEach((r) => {
      parts.push(`| ${r.risk} | \`${r.severity || "medium"}\` | ${r.mitigation} |`);
    });
    parts.push("");
  }

  parts.push(`## 🎤 Judging Pitch & Demo Walkthrough\n`);
  parts.push(`### 30-Second Elevator Pitch`);
  parts.push(`> "${plan.judgingPitch}"\n`);
  parts.push(`### Step-by-Step Demo Script`);
  parts.push(`${plan.demoScript}\n`);

  parts.push(`---\n*Generated by [Hackathon Copilot](https://github.com/kartikeykr007/Hack-Wave) powered by Google Gemma AI.*`);

  return parts.join("\n");
}

export function downloadMarkdown(filename: string, content: string) {
  const blob = new Blob([content], { type: "text/markdown;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.setAttribute("href", url);
  link.setAttribute("download", filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
